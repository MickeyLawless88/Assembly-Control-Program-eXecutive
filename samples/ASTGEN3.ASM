; ===========================================================================
; ASTEROID_CG.BIN  --  Asteroids game character generator ROM  (crasm, byte-exact)
;
; ASTGEN3: ASTGENII with enlarged ship/rock/bullet glyphs ($01-$0C).
; Based on 129867-1.bin (the ADM-31's standard character generator), with 12
; custom glyphs overlaid for this game's ship/rock/bullet sprites, and codes
; $00 and $20 forced genuinely blank (both were non-blank stray pixels in the
; original -- $00 is what the whole screen defaults to after RESET's own clear
; loop, $20 is the explicit erase glyph used throughout SCRNOUT/ROCKERASE).
;
; Real addressing, confirmed against actual hardware (not assumed): 128
; characters ($00-$7F), 16 bytes each = 2048 bytes (2716). Bit 7 of any
; character code written to screen memory is ignored for addressing.
;   * one DB per scan line, top (row 0) to bottom (row 15)
; * MSB (bit 7) = leftmost dot, 1 = dot lit; glyphs 7 wide (bits 6-0)
; * rows 10-15 are blank stride padding for every glyph in this ROM
;
; Confirmed directly: the real ADM-31 keyboard sends $3E for Shift-. ('>' in
; standard ASCII); decoded under this addressing, $3E renders as a clean,
; symmetric '>' -- verified against a real hardware photo. Every one of this
; project's custom glyphs was previously placed above $7F (silently aliasing
; to its low-7-bit twin) and read using the wrong, 8-byte-per-character
; stride -- both mistakes were invisible in simulation, only visible on real
; hardware, which is why they went uncaught for so long.
;
; Custom entries below are marked CUSTOM; everything else is unmodified from
; 129867-1.bin. NONE of the custom glyphs have been confirmed against real
; hardware yet -- unverified until burned and photographed.
;
; Assemble: crasm -o out.srec ASTEROID_CG.ASM
;           srec_cat out.srec -o out.bin -binary   (-> 2048 bytes)
; ===========================================================================

